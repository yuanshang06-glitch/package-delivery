"""Opt-in synthetic stored-ZIP stress; never part of the ordinary CI suite.

Example from the repo root (needs roughly twice the fixture size in free disk):
  python -B tests/benchmark_large.py --work-dir /new/owned/fixture-dir --size-mib 4097 --report /path/result.json
Only generated data.bin/result.zip are removed afterwards; the JSON report remains.
"""
from __future__ import annotations

import argparse
import ctypes
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import time
import zipfile
from pathlib import Path


def peak_working_set(process):
    if os.name != "nt":
        return None
    from ctypes import wintypes

    class Counters(ctypes.Structure):
        _fields_ = [("cb", wintypes.DWORD), ("PageFaultCount", wintypes.DWORD)] + [
            (name, ctypes.c_size_t) for name in (
                "PeakWorkingSetSize", "WorkingSetSize", "QuotaPeakPagedPoolUsage",
                "QuotaPagedPoolUsage", "QuotaPeakNonPagedPoolUsage", "QuotaNonPagedPoolUsage",
                "PagefileUsage", "PeakPagefileUsage",
            )
        ]

    value = Counters()
    value.cb = ctypes.sizeof(value)
    call = ctypes.WinDLL("psapi").GetProcessMemoryInfo
    call.argtypes = [wintypes.HANDLE, ctypes.POINTER(Counters), wintypes.DWORD]
    call.restype = wintypes.BOOL
    if call(wintypes.HANDLE(int(process._handle)), ctypes.byref(value), value.cb):
        return value.PeakWorkingSetSize
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work-dir", required=True, type=Path, help="new dedicated directory; must not exist")
    parser.add_argument("--size-mib", required=True, type=int)
    parser.add_argument("--report", required=True, type=Path)
    args = parser.parse_args()
    if not 65 <= args.size_mib <= 8192:
        parser.error("size-mib must be 65..8192; large tests are opt-in")
    root = args.work_dir.absolute()
    root.mkdir(parents=True, exist_ok=False)
    size = args.size_mib * 1024 * 1024
    if shutil.disk_usage(root).free < size * 2 + 256 * 1024 * 1024:
        raise SystemExit("Insufficient free space for original plus stored ZIP and margin")
    report_path = args.report.absolute()
    if report_path.is_relative_to(root):
        raise SystemExit("Report must be outside the generated fixture directory")
    source = Path(__file__).resolve().parents[1]
    helper = source / "package-delivery/scripts/delivery.py"
    checker = source / "package-delivery/scripts/check_handoff.py"
    data = root / "data.bin"
    archive = root / "result.zip"
    report = {"version":"1.2.0-development","fixture":"synthetic repeated byte pattern, not a user engineering project", "os":platform.system(),"python":platform.python_version(),"logical_payload_bytes":size,"profile":"large","compression":"stored","memory_metric":"PeakWorkingSetSize of each Windows child process; excludes system file cache; null on other systems", "phases":[],"passed":False}
    block = bytes(range(256)) * 4096
    expected = hashlib.sha256()
    created_data = False
    created_archive = False

    def command(label, script, argv, expected_code=0):
        started = time.monotonic()
        p = subprocess.Popen([sys.executable,"-B","-X","utf8",str(script),*map(str,argv)],stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,encoding="utf-8")
        stdout, stderr = p.communicate()
        peak = peak_working_set(p)
        record = {"name":label,"exit_code":p.returncode,"seconds":round(time.monotonic()-started,3),"peak_working_set_bytes":peak}
        report["phases"].append(record)
        if p.returncode != expected_code:
            record["stderr"] = stderr[-2000:]
            raise AssertionError(label+" unexpected exit status")
        if peak is not None and peak > 128 * 1024 * 1024:
            raise AssertionError(label+" exceeded the 128MiB child working-set criterion")
        return json.loads(stdout if p.returncode == 0 else stderr)

    try:
        started = time.monotonic()
        with data.open("xb") as stream:
            created_data = True
            for _ in range(args.size_mib):
                stream.write(block)
                expected.update(block)
        report["fixture_creation_seconds"] = round(time.monotonic()-started,3)
        digest = expected.hexdigest()
        (root / "START-HERE.md").write_text("Synthetic large fixture. Verify with explicit --profile large; no user data.\n",encoding="utf-8")
        (root / "evidence.json").write_text(json.dumps({"kind":"static","observation":"Synthetic bytes generated by benchmark","bytes":size,"sha256":digest})+"\n",encoding="utf-8")
        metadata = {"schema_version":"collaborator-delivery/1","task_id":"large-file-stress","title":"Synthetic large-file stress","status":"completed","summary":"Synthetic fixture for bounded stored ZIP64 processing","independent_acceptance":"UNKNOWN","files":["START-HERE.md","data.bin","evidence.json"],"checks":[{"name":"Generated fixture digest","status":"passed","evidence":"evidence.json"}],"unfinished":[],"requirements":["package-delivery 1.2 with explicit large profile"],"next_steps":["Verify with large profile"],"traceability":{"schema_version":"collaborator-traceability/1","criteria":[{"id":"AC1","requirement":"Synthetic file bytes and digest preserved","status":"met","artifacts":["data.bin"],"verification_ids":["V1"],"reason":None}],"verifications":[{"id":"V1","kind":"static","execution":"current","status":"passed","command":["python","tests/benchmark_large.py","--size-mib",str(args.size_mib)],"cwd":".","environment":{"os":platform.system(),"python":platform.python_version()},"exit_code":0,"evidence":"evidence.json","subjects":[{"path":"data.bin","sha256":digest}],"reason":None,"source":None}],"revision":None}}
        (root / "DELIVERY.json").write_text(json.dumps(metadata),encoding="utf-8")
        denied = command("standard-pack-refuses-large-member",helper,["pack","--root",root,"--out",archive],expected_code=1)
        assert denied["error"] in {"FILE_LIMIT","TOTAL_LIMIT"} and not archive.exists()
        created_archive = True
        packed = command("large-stored-pack-and-internal-verification",helper,["pack","--root",root,"--out",archive,"--profile","large","--compression","stored"])
        assert archive.stat().st_size > size
        checked = command("large-explicit-verification",helper,["verify",archive,"--profile","large"])
        assert checked == packed
        traced = command("large-traceability",checker,[archive,"--profile","large"])
        assert traced["archive_sha256"] == packed["archive_sha256"]
        command("standard-verify-refuses-large-archive",helper,["verify",archive],expected_code=1)
        with zipfile.ZipFile(archive) as z:
            info = z.getinfo("data.bin")
            assert info.file_size == size and info.compress_type == zipfile.ZIP_STORED
            manifest = json.loads(z.read("MANIFEST.json"))
            row = next(item for item in manifest["files"] if item["path"] == "data.bin")
            assert row["bytes"] == size and row["sha256"] == digest
            report["member_extract_version"] = info.extract_version
        with archive.open("rb") as stream:
            stream.seek(max(0,archive.stat().st_size-256))
            tail = stream.read(256)
        report.update(archive_bytes=archive.stat().st_size,archive_sha256=packed["archive_sha256"],source_sha256=digest,zip64_eocd_present=b"PK\x06\x06" in tail,zip64_locator_present=b"PK\x06\x07" in tail,uncompressed_total_bytes=packed["total_bytes"])
        if size > 4 * 1024**3:
            assert report["zip64_eocd_present"] and report["zip64_locator_present"] and report["member_extract_version"] >= 45
        report["passed"] = True
    finally:
        # Only our fixed generated large files are removed, never the directory recursively.
        if created_archive and archive.exists():
            archive.unlink()
        if created_data and data.exists():
            data.unlink()
        report["large_generated_files_removed"] = not data.exists() and not archive.exists()
        report_path.parent.mkdir(parents=True,exist_ok=True)
        report_path.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(json.dumps({"passed":report["passed"],"payload_bytes":size,"archive_bytes":report.get("archive_bytes"),"peak_child_bytes":max((x["peak_working_set_bytes"] or 0 for x in report["phases"]),default=0),"report":str(report_path)}))


if __name__ == "__main__":
    main()
